from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_BREAK_TYPE
import os

def insert_page_break_before(doc, text_trigger):
    for i, p in enumerate(doc.paragraphs):
        if text_trigger in p.text:
            # Вставляем разрыв страницы прямо перед этим абзацем
            p.insert_paragraph_before().add_run().add_break(WD_BREAK_TYPE.PAGE)
            print(f"Вставлен разрыв страницы перед: '{p.text[:40]}...'")
            break

