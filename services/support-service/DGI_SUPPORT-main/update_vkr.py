def set_cell_margins(cell, top=100, bottom=100, left=150, right=150):
    """Установка полей в ячейках таблицы"""
    tcPr = cell._tc.get_or_add_tcPr()
    tcMar = OxmlElement('w:tcMar')
    for m, val in [('w:top', top), ('w:bottom', bottom), ('w:left', left), ('w:right', right)]:
        node = OxmlElement(m)
        node.set(qn('w:w'), str(val))
        node.set(qn('w:type'), 'dxa')
        tcMar.append(node)
    tcPr.append(tcMar)

def format_run(run, font_name="Times New Roman", size_pt=14, bold=False, italic=False, color=RGBColor(0, 0, 0)):
    run.font.name = font_name
    run.font.size = Pt(size_pt)
    run.bold = bold
    run.italic = italic
    run.font.color.rgb = color

def format_paragraph(paragraph, align=WD_ALIGN_PARAGRAPH.JUSTIFY, line_spacing=1.5, space_after=0, space_before=0, first_line_indent=1.25):
    paragraph.alignment = align
    paragraph.paragraph_format.line_spacing = line_spacing
    paragraph.paragraph_format.space_after = Pt(space_after)
    paragraph.paragraph_format.space_before = Pt(space_before)
    if first_line_indent:
        paragraph.paragraph_format.first_line_indent = Inches(first_line_indent / 2.54)

def set_font_style(doc):
    """Настройка шрифта всего документа на Times New Roman 14pt"""
    for paragraph in doc.paragraphs:
        # Проверим, не пустой ли абзац
        if paragraph.text.strip():
            format_paragraph(paragraph)
            for run in paragraph.runs:
                # Сохраняем полужирный/курсив, если они уже были
                is_bold = run.bold
                is_italic = run.italic
                format_run(run, bold=is_bold, italic=is_italic)
    
    # Настройка колонтитулов (12 пт)
    for section in doc.sections:
        header = section.header
        if header:
            for p in header.paragraphs:
                format_paragraph(p, align=WD_ALIGN_PARAGRAPH.RIGHT, first_line_indent=0)
                for run in p.runs:
                    format_run(run, size_pt=12)
        footer = section.footer
        if footer:
            for p in footer.paragraphs:
                format_paragraph(p, align=WD_ALIGN_PARAGRAPH.CENTER, first_line_indent=0)
                for run in p.runs:
                    format_run(run, size_pt=12)

